const { chromium, expect } = require('@playwright/test');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const results = [];
  for (const width of [320,428]) for (const size of [16,32]) {
    const page = await browser.newPage({ viewport: { width, height: 850 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const url = 'http://127.0.0.1:5192';
    async function load(path) { await page.goto(url+path); await page.evaluate(n => document.documentElement.style.fontSize=n+'px',size); }
    async function check(name) {
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      expect(errors).toEqual([]);
      await page.screenshot({ path: `outputs/qss-personal-space-p2/${name}-${width}-${size}.png`, fullPage: true });
      results.push({ name, width, text: size===16?'100%':'200%', status: 'PASS' });
    }
    await load('/?fixture=empty');
    await expect(page.getByText('まだ台本がありません。', {exact:false})).toBeVisible();
    await check('empty-home');
    await load('/takes?fixture=empty');
    await expect(page.getByText('保存済みTakeはまだありません。')).toBeVisible();
    await check('empty-takes');
    await load('/?fixture=one');
    await expect(page.locator('.space-counts button').last()).toHaveText('0お気に入り');
    await expect(page.locator('#space-favorites-title')).toHaveCount(0);
    await expect(page.locator('.space-own-takes li')).toHaveCount(1);
    await check('one-home');
    await page.locator('.space-own-takes li button').click();
    await expect(page.locator('.take-identity')).toContainText('台本: A small pause');
    await expect(page.getByRole('button', {name:'♡ お気に入り',exact:true})).toHaveAttribute('aria-pressed','false');
    await expect(page.locator('.space-bottom-nav')).toHaveCount(0);
    await check('review-unnamed');
    await page.evaluate(() => window.p2QA.delay=350);
    await page.getByRole('button',{name:'♡ お気に入り',exact:true}).evaluate(el => { el.click(); el.click(); el.click(); });
    await expect(page.getByRole('button',{name:'♡ お気に入り',exact:true})).toBeDisabled();
    await expect(page.getByRole('button',{name:'♥ お気に入り',exact:true})).toHaveAttribute('aria-pressed','true');
    expect(await page.evaluate(() => window.p2QA.calls)).toBe(1);
    await page.getByRole('button',{name:'名前をつける',exact:true}).click();
    await page.getByLabel('録音名（60文字まで）').fill('  My favorite voice  ');
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await expect(page.getByRole('button',{name:'キャンセル',exact:true})).toBeDisabled();
    await expect(page.locator('.take-identity h2')).toHaveText('My favorite voice');
    await expect(page.locator('.take-identity')).toContainText('台本: A small pause');
    await check('review-named');
    await page.reload();
    await expect(page.locator('.take-identity h2')).toHaveText('My favorite voice');
    await expect(page.getByRole('button',{name:'♥ お気に入り',exact:true})).toHaveAttribute('aria-pressed','true');
    await page.getByRole('button',{name:'録音履歴を見る',exact:true}).click();
    await expect(page.locator('.space-takes li')).toHaveCount(1);
    await expect(page.locator('.space-takes')).toContainText('My favorite voice');
    await expect(page.locator('.space-takes')).toContainText('台本: A small pause');
    await page.getByRole('button',{name:'お気に入り',exact:true}).click();
    await expect(page.locator('.space-takes li')).toHaveCount(1);
    await check('favorites-takes');
    await page.getByRole('button',{name:'Home',exact:true}).click();
    await expect(page.locator('.space-counts button').last()).toHaveText('1お気に入り');
    await expect(page.locator('[aria-labelledby="space-favorites-title"]')).toContainText('My favorite voice');
    await expect(page.locator('.space-last')).toContainText('同じ台本の最高点 82点');
    await check('favorite-home');
    await page.locator('.space-counts button').last().click();
    await expect(page.getByRole('button',{name:'お気に入り',exact:true})).toHaveAttribute('aria-pressed','true');
    await page.locator('.space-takes li button').click();
    await page.getByRole('button',{name:'♥ お気に入り',exact:true}).click();
    await expect(page.getByRole('button',{name:'♡ お気に入り',exact:true})).toHaveAttribute('aria-pressed','false');
    await page.getByRole('button',{name:'名前を変更',exact:true}).click();
    const long = '<b>'+'長い録音名'.repeat(10)+'</b>';
    await page.getByLabel('録音名（60文字まで）').fill(long);
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await expect(page.locator('.take-identity h2')).toHaveText(long);
    await expect(page.locator('.take-identity h2 b')).toHaveCount(0);
    await check('long-name');
    await page.getByRole('button',{name:'名前を変更',exact:true}).click();
    await page.getByLabel('録音名（60文字まで）').fill('');
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await expect(page.locator('.take-identity h2')).toHaveCount(0);
    await page.evaluate(() => window.p2QA.failUpdate=true);
    await page.getByRole('button',{name:'♡ お気に入り',exact:true}).click();
    await expect(page.getByText('保存を確認できませんでした。', {exact:false})).toBeVisible();
    await expect(page.getByRole('button',{name:'♡ お気に入り',exact:true})).toHaveAttribute('aria-pressed','false');
    await check('update-failure');
    await page.evaluate(() => window.p2QA.failUpdate=false);
    await page.getByRole('button',{name:'再試行',exact:true}).click();
    await expect(page.getByRole('button',{name:'♡ お気に入り',exact:true})).toBeEnabled();
    await page.evaluate(() => { window.p2QA.delay=500; });
    await page.getByRole('button',{name:'♡ お気に入り',exact:true}).click();
    await page.getByRole('button',{name:'練習を終了（Home）',exact:true}).click();
    await expect(page.locator('.home-screen')).toBeVisible();
    // Pending old screen completion must not bring back Review or change its state.
    await page.waitForTimeout(600);
    await expect(page.locator('.review-screen')).toHaveCount(0);
    await check('stale-response');
    await load('/takes?fixture=populated&filter=favorites');
    await expect(page.getByText('お気に入りの録音はまだありません。', {exact:false})).toBeVisible();
    await check('zero-favorites');
    await page.getByRole('button',{name:'すべて',exact:true}).click();
    await expect(page.locator('.space-takes li')).toHaveCount(6);
    await expect(page.locator('.space-takes li').first()).toContainText('スコア 82');
    await check('all-order');
    await load('/?fixture=error');
    await expect(page.getByRole('heading',{name:'記録を読み込めませんでした'})).toBeVisible();
    await expect(page.locator('.space-counts')).toHaveCount(0);
    await check('read-failure');
    await page.close();
  }
  fs.writeFileSync('outputs/qss-personal-space-p2/browser-results.json',JSON.stringify(results,null,2));
  await browser.close();
  console.log(`${results.length} P2 browser conditions PASS`);
})().catch(error => { console.error(error); process.exit(1); });
